-- stats.export_limited_rows의 표시 이름·설명을 실제 동작에 맞게 바꾼다(키는 그대로 —
-- grant 행·코드의 hasCapability 판정은 영향 없음).
--
-- 0028의 원래 문구("행 단위 제한데이터 내보내기 / 직접식별자 제거 행 단위 export")는
-- 아직 구현되지 않은 행 단위 파일 내보내기(PR5)를 가리켰지만, 이 권한이 실제로 여는 것은
-- 분석 화면 응답에 붙는 원본 값(이상치 원값·산점도 원시 점·회귀 관측치 진단값)이다.
-- 히스토그램 끝 구간 병합 PR에서 원본 히스토그램(rawHistogram)까지 같은 권한으로 열리게
-- 되어, 관리자 콘솔 "통계 권한" 탭에서 무엇을 부여하는지 정확히 보이도록 고친다.
UPDATE capabilities
SET label = '제한 데이터 열람(원본 값·원본 히스토그램)',
    description = '분석 화면에 소수 인원 보호를 거치지 않은 원본 값을 표시: 이상치 원값·산점도 원시 점·회귀 관측치 진단값·원본 히스토그램. 응답마다 감사 기록, 결과 캐시에는 저장 안 함. 행 단위 파일 내보내기는 아님'
WHERE key = 'stats.export_limited_rows';
