-- stats.export_limited_rows 설명 갱신(0035 후속). 키·표시명은 그대로 — grant 행과 코드의
-- hasCapability 판정은 영향 없음.
--
-- 이 권한이 기술통계(일반 + 담당의 층화)의 소수 셀(고유 인원 1~9명) 제한까지 풀게 되어, 권한을 부여하는
-- 관리자가 의미를 오해하지 않도록 관리자 콘솔 "통계 권한" 탭의 설명에 명시한다. 해제는 응답 시점에만
-- 적용되고 결과 캐시에는 저장되지 않으며, 응답마다 감사 기록이 남는다.
UPDATE capabilities
SET description = '분석 화면에 소수 인원 보호를 거치지 않은 원본 값을 표시: 이상치 원값·산점도 원시 점·회귀 관측치 진단값·원본 히스토그램·원본 범주 빈도. 기술통계(담당의별 표 포함)에서는 고유 인원 10명 미만 셀·그룹·결측 건수의 비공개·병합도 해제. 응답마다 감사 기록, 결과 캐시에는 저장 안 함. 행 단위 파일 내보내기는 아님'
WHERE key = 'stats.export_limited_rows';
