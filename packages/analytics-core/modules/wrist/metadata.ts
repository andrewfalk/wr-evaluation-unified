function wristJobDiagnosisDependsOn(fields: string[], { includeProvenance = true }: { includeProvenance?: boolean } = {}): string[] {
  const perField = fields.flatMap((field) => [
    `modules.wrist.jobEvaluations[].diagnosisEntries[].${field}`,
    `modules.wrist.diagnosisEvaluations[].${field}`,
  ]);
  const provenance = includeProvenance ? ['modules.wrist.jobEvaluations[].diagnosisEntries[].bkAutoSyncedFrom'] : [];
  return [...JOB_DIAGNOSIS_BASE_DEPENDS_ON, ...perField, ...provenance];
}

